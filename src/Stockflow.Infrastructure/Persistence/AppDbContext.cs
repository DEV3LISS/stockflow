using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage;
using Stockflow.Application.Abstractions;
using Stockflow.Domain.Auth;
using Stockflow.Domain.Carts;
using Stockflow.Domain.Catalog;
using Stockflow.Domain.Common;
using Stockflow.Domain.Inventory;
using Stockflow.Domain.Orders;
using Stockflow.Domain.Payments;
using Stockflow.Domain.Users;

namespace Stockflow.Infrastructure.Persistence;

public sealed class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options), IAppDbContext
{
    public DbSet<User> Users => Set<User>();
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();
    public DbSet<Category> Categories => Set<Category>();
    public DbSet<Product> Products => Set<Product>();
    public DbSet<StockItem> StockItems => Set<StockItem>();
    public DbSet<InventoryMovement> InventoryMovements => Set<InventoryMovement>();
    public DbSet<Cart> Carts => Set<Cart>();
    public DbSet<Order> Orders => Set<Order>();
    public DbSet<Payment> Payments => Set<Payment>();
    public DbSet<ProcessedWebhookEvent> ProcessedWebhookEvents => Set<ProcessedWebhookEvent>();

    public Task<IDbContextTransaction> BeginTransactionAsync(CancellationToken cancellationToken = default) =>
        Database.BeginTransactionAsync(cancellationToken);

    public async Task<Order?> LockOrderAsync(Guid id, CancellationToken cancellationToken = default)
    {
        // xmin must be selected explicitly: "SELECT *" does not return system columns (lesson from Torque CRM).
        var order = await Orders.FromSql($"SELECT *, xmin FROM orders WHERE id = {id} FOR UPDATE").SingleOrDefaultAsync(cancellationToken);
        if (order is not null)
        {
            await Entry(order).Collection(o => o.Lines).LoadAsync(cancellationToken);
        }

        return order;
    }

    public async Task<IReadOnlyList<Order>> LockExpiredOrdersAsync(DateTimeOffset now, int batchSize, CancellationToken cancellationToken = default)
    {
        var orders = await Orders
            .FromSql($"""
                SELECT *, xmin FROM orders
                WHERE status = 'PendingPayment' AND reserved_until <= {now}
                ORDER BY reserved_until
                LIMIT {batchSize}
                FOR UPDATE SKIP LOCKED
                """)
            .ToListAsync(cancellationToken);

        foreach (var order in orders)
        {
            await Entry(order).Collection(o => o.Lines).LoadAsync(cancellationToken);
        }

        return orders;
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasPostgresExtension("pg_trgm");
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        // Ids are generated by the application (UUIDv7) — see Torque CRM ADR-017 for the bug this prevents.
        foreach (var entity in modelBuilder.Model.GetEntityTypes().Where(e => typeof(Entity).IsAssignableFrom(e.ClrType)))
        {
            modelBuilder.Entity(entity.ClrType).Property(nameof(Entity.Id)).ValueGeneratedNever();
        }
    }

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder) =>
        configurationBuilder.Properties<Enum>().HaveConversion<string>().HaveMaxLength(32);
}
